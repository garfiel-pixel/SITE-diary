// Generates src/pdf/pdfFonts.ts — a pdfmake Virtual File System with the
// self-hosted Barlow TTFs embedded (base64). Run: node scripts/make-fonts.mjs
import fs from "node:fs";
import path from "node:path";
import URL from "node:url";

const __dirname = path.dirname(URL.fileURLToPath(import.meta.url));
const fontDir = path.join(__dirname, "..", "src", "pdf", "fonts");
const outFile = path.join(__dirname, "..", "src", "pdf", "pdfFonts.ts");

const files = fs
  .readdirSync(fontDir)
  .filter((f) => f.endsWith(".ttf"));
const entries = files.map((f) => {
  const b64 = fs.readFileSync(path.join(fontDir, f)).toString("base64");
  return `  "${f}": "${b64}",`;
});

// Byte-for-byte logo for the PDF header (base64 round-trip is lossless).
const logoSrc = path.join(__dirname, "..", "..", "Gemini_Generated_Image_81zzia81zzia81zz.jpg");
const logoB64 = fs.readFileSync(logoSrc).toString("base64");

const ts = `/* GENERATED by scripts/make-fonts.mjs — self-hosted Barlow TTFs, plus the
   supplied logo artwork (byte-for-byte base64 round-trip, lossless), for
   pdfmake. Do not edit; regenerate. Builds fully offline. */

export const vfs: Record<string, string> = {
${entries.join("\n")}

  // the supplied logo artwork, byte-for-byte (base64 lossless round-trip)
  "logo.jpg": "${logoB64}",
};
`;
fs.writeFileSync(outFile, ts);
console.log(`make-fonts: wrote ${outFile} with ${files.length} fonts`);
