import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 400, height: 800 } });
await page.goto("http://localhost:4173/");
await page.getByLabel("Activation code character 1 of 12").click();
await page.keyboard.type("PAVECON-DEMO", { delay: 5 });
await page.getByRole("button", { name: "ACTIVATE" }).click();
await page.waitForTimeout(500);
await page.getByTestId("start-blank").click();
await page.locator("#sec-equipment > h2 > button").click();
await page.getByRole("button", { name: "Add Paver" }).click();
const slider = page.locator('[role="slider"][aria-label="Paver hours"]');
await slider.focus();
await page.keyboard.press("End");
const minus = page.locator('#sec-equipment button[aria-label="Decrease"]').first();
await minus.evaluate((el) => el.scrollIntoView({ block: "center", behavior: "instant" }));
await page.waitForTimeout(200);
const box = await minus.boundingBox();
console.log("box", box);
console.log("at point", await page.evaluate(([x, y]) => {
  const el = document.elementFromPoint(x, y);
  return { tag: el?.tagName, aria: el?.getAttribute("aria-label"), cls: el?.className, parentAria: el?.parentElement?.getAttribute("aria-label") };
}, [box.x + box.width / 2, box.y + box.height / 2]));
console.log("before", await slider.getAttribute("aria-valuenow"));
await minus.dispatchEvent("pointerdown", { pointerId: 1, isPrimary: true, button: 0 });
await page.waitForTimeout(1500);
await minus.dispatchEvent("pointerup", { pointerId: 1, isPrimary: true, button: 0 });
console.log("after dispatch hold", await slider.getAttribute("aria-valuenow"));
await browser.close();
